"""Generate simulation/orchestrator/signals.add.xml from the real network.

The GreenCorridor sample network's tlLogic programs use yellow phases that also
carry pedestrian 'G' signals (e.g. ``yyyrrrGyy``) and have no all-red phase.
TrafficMind classifies any phase containing 'G'/'g' as a green stage, so it sees
phantom 3 s stages and (correctly) refuses to advise changes.

This script rewrites *the same* state strings -- same number of links, same
movement mapping, same phase order -- with:
  * pedestrian greens cleared to red during yellow,
  * an explicit all-red clearance phase after every yellow,
  * minDur/maxDur so SUMO itself enforces the green bounds.

Nothing about the movement mapping is invented: every state string is copied
from grid.net.xml and only 'G'/'g' characters inside clearance phases are
replaced by 'r'.
"""
from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_NET = REPO_ROOT / "simulation/green_corridor/sample_network/grid.net.xml"
DEFAULT_OUT = REPO_ROOT / "simulation/orchestrator/signals.add.xml"

GREEN_CHARS = frozenset("Gg")
YELLOW_CHARS = frozenset("Yy")

PROGRAM_ID = "orchestrator"

GREEN_MIN_S = 15
GREEN_MAX_S = 60
YELLOW_S = 3
ALL_RED_S = 2


def _green_positions(state: str) -> set[int]:
    return {i for i, c in enumerate(state) if c in GREEN_CHARS}


def _is_clearance(state: str, previous: str | None) -> bool:
    """True for a yellow phase, including one that keeps pedestrian greens.

    In this network the yellow phases also leave pedestrian links green
    (``yyyrrrGyy``). Such a phase is still a clearance phase: the only greens it
    keeps are a subset of the greens the preceding phase already served.
    """
    if not any(c in YELLOW_CHARS for c in state):
        return False
    if previous is None:
        return not _green_positions(state)
    return _green_positions(state) <= _green_positions(previous)


def build(net_path: Path, out_path: Path) -> int:
    root = ET.parse(net_path).getroot()
    out_root = ET.Element("additional")
    count = 0
    for tl in root.findall("tlLogic"):
        tls_id = tl.get("id")
        new_tl = ET.SubElement(out_root, "tlLogic", {
            "id": tls_id,
            "type": "static",
            "programID": PROGRAM_ID,
            "offset": "0",
        })
        previous_state: str | None = None
        for phase in tl.findall("phase"):
            state = phase.get("state", "")
            duration = float(phase.get("duration", "0"))
            if _is_clearance(state, previous_state):
                cleared = "".join("r" if c in GREEN_CHARS else c for c in state)
                ET.SubElement(new_tl, "phase", {
                    "duration": str(YELLOW_S),
                    "minDur": str(YELLOW_S),
                    "maxDur": str(YELLOW_S),
                    "state": cleared,
                })
                ET.SubElement(new_tl, "phase", {
                    "duration": str(ALL_RED_S),
                    "minDur": str(ALL_RED_S),
                    "maxDur": str(ALL_RED_S),
                    "state": "r" * len(state),
                })
            elif any(c in GREEN_CHARS for c in state):
                ET.SubElement(new_tl, "phase", {
                    "duration": str(int(duration)),
                    "minDur": str(GREEN_MIN_S),
                    "maxDur": str(GREEN_MAX_S),
                    "state": state,
                })
            else:
                # Already a pure all-red phase: keep it as-is.
                ET.SubElement(new_tl, "phase", {
                    "duration": str(int(duration)),
                    "minDur": str(int(duration)),
                    "maxDur": str(int(duration)),
                    "state": state,
                })
            previous_state = state
        count += 1

    ET.indent(out_root, space="    ")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        fh.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        fh.write("<!-- Generated by scripts/build_signal_programs.py from grid.net.xml.\n")
        fh.write("     Same link mapping as the network; pedestrian greens cleared during\n")
        fh.write("     yellow, explicit all-red added, green bounds declared. -->\n")
        fh.write(ET.tostring(out_root, encoding="unicode"))
        fh.write("\n")
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--net", type=Path, default=DEFAULT_NET)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    n = build(args.net, args.out)
    print(f"wrote {n} tlLogic programs to {args.out}")


if __name__ == "__main__":
    main()
